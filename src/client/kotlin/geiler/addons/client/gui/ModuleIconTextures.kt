    fun sourceSize(moduleName: String): Int = sourceSizes[moduleName] ?: 64

    private fun icon(file: String, gui: Boolean = false): Identifier =
        Identifier.fromNamespaceAndPath(
            "geileraddons",
            "textures/${if (gui) "gui" else "module_icons"}/$file.png",
        )
